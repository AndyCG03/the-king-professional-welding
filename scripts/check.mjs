import {readFile, access} from 'node:fs/promises';
import {join} from 'node:path';
const html = await readFile('dist/index.html','utf8');
const assets = [...html.matchAll(/(?:src|href)="(\/(?!\/)[^"#?]+)"/g)].map(m=>m[1]);
for (const asset of assets) await access(join('dist',asset));
const ids = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]));
for (const match of html.matchAll(/href="#([^"]+)"/g)) if (!ids.has(match[1])) throw new Error(`Missing anchor: ${match[1]}`);
for (const field of ['832-732-7616','21126 Terrace View Dr','Thekingofprofessionalwelding@gmail.com']) if (!html.includes(field)) throw new Error(`Missing business detail: ${field}`);
for (const match of html.matchAll(/<img\b([^>]+)>/g)) if (!/\balt="[^"]+"/.test(match[1])) throw new Error('Missing image alt text');
JSON.parse(await readFile('vercel.json','utf8'));
console.log(`OK: ${assets.length} local asset references, navigation anchors, image descriptions, business details and Vercel JSON.`);
